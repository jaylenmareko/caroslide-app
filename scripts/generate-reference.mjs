// Same fix, same reason as generate-templates.mjs: Cloudflare Workers has no real filesystem at
// runtime -- fs.readFile() against a bundled reference doc throws ENOENT there (confirmed live
// 2026-07-31: a real production carousel generation failed with
// "no such file or directory, readAll '/bundle/reference/content-strategies.md'"). generateCaptions
// (captions.ts) read these three docs via readFile(path.join(process.cwd(), 'reference', ...)) --
// exactly the pattern generate-templates.mjs's own comment already warned doesn't survive
// bundling, just never applied to these files. Generating a plain TS module of string constants
// sidesteps this entirely -- it's ordinary code, so it survives every bundler pass (Next/Turbopack,
// OpenNext's esbuild, Wrangler's esbuild) exactly like any other import.
// Run automatically before `dev`/`build` (see package.json) so this can never go stale relative to
// the real .md source files, which stay the actual, directly-edited source of truth.
import { readFile, writeFile } from 'fs/promises'
import path from 'path'
import { fileURLToPath } from 'url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const REFERENCE_DIR = path.join(__dirname, '..', 'reference')
const OUT_FILE = path.join(__dirname, '..', 'src', 'backend', 'lib', 'generation', 'referenceDocs.generated.ts')

const files = ['content-strategies.md', 'templates-guide.md', 'initial-generation-behavior.md']

const entries = await Promise.all(
  files.map(async (file) => {
    const content = await readFile(path.join(REFERENCE_DIR, file), 'utf-8')
    return `  ${JSON.stringify(file)}: ${JSON.stringify(content)},`
  })
)

const out = `// Auto-generated by scripts/generate-reference.mjs -- do not edit by hand.
// Edit the .md files in reference/ instead; this file regenerates on every dev/build.
export const REFERENCE_DOCS: Record<string, string> = {
${entries.join('\n')}
}
`

await writeFile(OUT_FILE, out, 'utf-8')
console.log(`Generated ${OUT_FILE} (${files.length} reference docs)`)
