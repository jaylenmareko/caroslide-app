// Cloudflare Workers has no real filesystem at runtime -- fs.readFile() against a bundled
// template file throws ENOENT there (confirmed live 2026-07-26: Next's own output-file-tracing
// copies the .html files into `.open-next/server-functions/default/...` for reference, but that's
// unrelated to what actually ends up in the Worker's bundle, and no bundler traces a runtime
// fs.readFile(path) call the way it traces a static import). Generating a plain TS module of string
// constants sidesteps this entirely -- it's ordinary code, so it survives every bundler pass
// (Next/Turbopack, OpenNext's esbuild, Wrangler's esbuild) exactly like any other import.
// Run automatically before `dev`/`build` (see package.json) so this can never go stale relative to
// the real .html source files, which stay the actual, directly-edited source of truth.
import { readdir, readFile, writeFile } from 'fs/promises'
import path from 'path'
import { fileURLToPath } from 'url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const TEMPLATES_DIR = path.join(__dirname, '..', 'src', 'backend', 'lib', 'generation', 'templates')
const OUT_FILE = path.join(TEMPLATES_DIR, 'index.generated.ts')

const files = (await readdir(TEMPLATES_DIR)).filter((f) => f.endsWith('.html')).sort()

const entries = await Promise.all(
  files.map(async (file) => {
    const content = await readFile(path.join(TEMPLATES_DIR, file), 'utf-8')
    return `  ${JSON.stringify(file)}: ${JSON.stringify(content)},`
  })
)

const out = `// Auto-generated by scripts/generate-templates.mjs -- do not edit by hand.
// Edit the .html files in this folder instead; this file regenerates on every dev/build.
export const TEMPLATES: Record<string, string> = {
${entries.join('\n')}
}
`

await writeFile(OUT_FILE, out, 'utf-8')
console.log(`Generated ${OUT_FILE} (${files.length} templates)`)
